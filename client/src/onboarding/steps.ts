const step = (
  partial: Omit<OnboardingStep, 'targetSelector' | 'highlight' | 'position'> & {
    targetSelector?: string;
    path?: string;
  }
): OnboardingStep => ({
  targetSelector: 'body',
  highlight: false,
  position: 'center',
  ...partial,
});

