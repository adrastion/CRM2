export function getOnboardingSteps(role: string): OnboardingStep[] {
  switch (role) {
    case 'OWNER':
      return [
        welcome([
          'Вы — владелец: полный доступ ко всем разделам и настройкам.',
        ]),
        ...ownerAdminCore,
        complete,
      ];
    case 'ADMIN':
      return [
        welcome([
          'Вы — администратор: почти полный доступ, как у владельца (кроме отдельных ограничений).',
        ]),
        ...adminStepsFiltered,
        complete,
      ];
    case 'TRAINER':
      return [
        welcome(['Вы — тренер: фокус на группах, расписании и заработке.']),
        ...trainerSteps,
        trainerComplete,
      ];
    case 'PROMOTER':
      return [
        welcome(['Вы — промоутер: доступ ограничен вашими клиентами.']),
        ...promoterSteps,
        promoterComplete,
      ];
    default:
      return [welcome([]), complete];
  }
}
